--   engine_set / engine_clear   engine flags  (constants/engine_flags.asm):
--                               badges, Pokegear cards, Pokedex, fly points...
--   scenes                      final value of each map scene variable that
--                               changed. 3.2.3 has no SCENE_* names, so the
--                               values are numbers (data/maps/scenes.asm)
--   key_items, tms_hms, items   received in this stretch and still held at
--                               its end (items as { NAME, count })
--   taken                       items given in an EARLIER checkpoint that a
--                               script took back in this one
--   phone_numbers               numbers added by story scripts (extra)
--   pokemon_received            Pokemon given by scripts (extra; the party
--                               below already includes them)
--
-- These two are NOT changes, they describe the whole save at that point:
--   money_hint                  total money, rough (earned from main-path
--                               battles and gifts; ignores shopping)
--   party_hint                  a plausible whole party { SPECIES, level }
--
--   at                          where to stand: map constant + tile x, y
--                               (same coordinates as warp_event/object_event)
--   sources                     file:line in the 3.2.3 source for each entry
--                               (keys: flag/item name, "scene:MAP",
--                               "taken:ITEM", "pokemon:SPECIES")
--   unsure                      guesses and open questions
